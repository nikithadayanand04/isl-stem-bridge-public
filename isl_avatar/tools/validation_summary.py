"""One table of every sign's validation results, built from the report files (never typed by hand).

    python3 tools/validation_summary.py            # writes reports/VALIDATION_SUMMARY.md

Reads registry/signs.csv, motion/v2/*.json (QC re-run), reports/v2/<sign>/report.json,
reports/baseline/<sign>/report.json, reports/rig/rig_report.json and reports/face/face_report.json.
"""

import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'tools'))
import motion_qc  # noqa: E402
import check_registry as cr  # noqa: E402


def load(path):
    try:
        return json.loads(Path(path).read_text(encoding='utf-8'))
    except (OSError, ValueError):
        return None


def med(r, side, key):
    try:
        return r[side][key]['median']
    except (KeyError, TypeError):
        return None


def fmt(v, unit=''):
    return '–' if v is None else f'{v}{unit}'


def main():
    rows = cr.read_rows(ROOT / 'registry' / 'signs.csv')
    import datetime
    _, results = cr.check(rows, ROOT, datetime.date.today())
    stages = {r['sign_id']: r['stages'] for r in results}
    status = {r['sign_id']: r['status'] for r in results}
    rig = load(ROOT / 'reports' / 'rig' / 'rig_report.json') or {}
    rig_before = load(ROOT / 'reports' / 'rig_before_thumb_fix' / 'rig_report.json') or {}
    face = load(ROOT / 'reports' / 'face' / 'face_report.json') or {}

    out = ['# Validation summary', '',
           f'Generated by `tools/validation_summary.py` on {datetime.date.today().isoformat()} from the report files.',
           'Geometric numbers compare the avatar with the landmarks tracked from the source video; they say',
           'nothing about whether the signing is correct ISL. Only interpreter approval does.', '',
           '## Stages per sign', '',
           '| Sign | Source | Motion QC | Retarget | Geometric | Interp. reviewed | Interp. approved | Published | Status |',
           '| --- | --- | --- | --- | --- | --- | --- | --- | --- |']
    mark = {True: '✓', False: '✗'}
    for r in rows:
        st = stages[r['sign_id']]
        out.append(f'| {r["sign_id"]} | ' + ' | '.join(mark[st[s]] for s in cr.STAGES) + f' | {status[r["sign_id"]]} |')

    out += ['', '## Motion quality (re-run with current rules)', '',
            '| Sign | Result | Longest lost run (L / R) | Depth-flipped frames (L / R) | Recording warnings |',
            '| --- | --- | --- | --- | --- |']
    for f in sorted((ROOT / 'motion' / 'v2').glob('*.json')):
        q = motion_qc.qc_report(load(f))
        h = q['hands']

        def side(key, field):
            v = h.get(key, {})
            return str(len(v.get(field, [])) if isinstance(v.get(field), list) else v.get(field, '–')) if v.get('signing') else '–'
        out.append(f'| {f.stem} | {q["result"]} | {side("left_hand", "longest_gap_frames")} / {side("right_hand", "longest_gap_frames")} '
                   f'| {side("left_hand", "depth_flip_frames")} / {side("right_hand", "depth_flip_frames")} '
                   f'| {"; ".join(q["recording"]["warnings"]) or "none"} |')

    out += ['', '## Geometric comparison (current bake vs first pipeline)', '',
            'Median per side. Flexion and palm in degrees; wrist in fractions of the body measure.', '',
            '| Sign | Side | Flexion now | Flexion before | Palm now | Palm before | Wrist now | Wrist before | Speed corr. | Check |',
            '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |']
    for d in sorted((ROOT / 'reports' / 'v2').iterdir()):
        r = load(d / 'report.json')
        if not r:
            continue
        b = load(ROOT / 'reports' / 'baseline' / d.name / 'report.json')
        for s in ('left', 'right'):
            if s not in r:
                continue
            out.append(f'| {d.name} | {s} | {fmt(med(r, s, "finger_flexion_error_deg"))} | {fmt(med(b, s, "finger_flexion_error_deg"))} '
                       f'| {fmt(med(r, s, "palm_orientation_error_deg"))} | {fmt(med(b, s, "palm_orientation_error_deg"))} '
                       f'| {fmt(med(r, s, "wrist_position_error"))} | {fmt(med(b, s, "wrist_position_error"))} '
                       f'| {fmt(r[s].get("wrist_speed_correlation"))} | {r.get("geometric_check", {}).get("result", "–")} |')

    if rig:
        out += ['', '## Rig check on every baked sign', '',
                f'Detector controls passed: **{rig.get("detector_controls_passed")}**. Skin contact = overlap up to '
                '2 mm (skin pressing on skin); passing through = deeper.', '',
                ('"Before" is the bake without the thumb overlap correction (`reports/rig_before_thumb_fix/`).' if rig_before else ''),
                '',
                '| Sign | Side | Frames | Over joint limit | Skin contact | Passing through (before) | Mean depth mm, all frames (before) | Deepest mm (before) |',
                '| --- | --- | --- | --- | --- | --- | --- | --- |']
        for track, sides in sorted(rig.get('tracks', {}).items()):
            for s, v in sides.items():
                b = rig_before.get('tracks', {}).get(track, {}).get(s)
                pt = f'{v["frames_passing_through"]}' + (f' ({b["frames_passing_through"]})' if b else '')
                dp = fmt(v['worst'].get('depth_mm')) + (f' ({fmt(b["worst"].get("depth_mm"))})' if b else '')
                mn = fmt(v.get('mean_depth_all_frames_mm')) + (f' ({fmt(b.get("mean_depth_all_frames_mm"))})' if b else '')
                out.append(f'| {track} | {s} | {v["frames"]} | {v["frames_over_limit"]} | {v["frames_skin_contact"]} '
                           f'| {pt} | {mn} | {dp} |')
        out += ['', '### Test poses', '', '| Pose | Left | Right |', '| --- | --- | --- |']
        for n in dict.fromkeys(k.split(':')[1] for k in rig['poses']):
            cells = []
            for s in ('left', 'right'):
                e = rig['poses'].get(f'{s}:{n}')
                if not e:
                    cells.append('–')
                    continue
                txt = 'clean' if not e['overlap_depth_mm'] and not e['over_limit'] else \
                    ', '.join([f'{k} {v} mm' for k, v in e['overlap_depth_mm'].items()] +
                              ([f'{len(e["over_limit"])} joints over limit'] if e['over_limit'] else []))
                if 'control_detected' in e:
                    txt += f' (control {"caught" if e["control_detected"] else "MISSED"})'
                cells.append(txt)
            out.append(f'| {n} | {cells[0]} | {cells[1]} |')

    if face:
        out += ['', '## Face', '', f'ARKit shapes present: {face["arkit_present"]}/{face["arkit_expected"]} on `{face["face_mesh"]}`.',
                f'Eye bones: {face["gaze"]["eye_bones"] or "none"}; eyeball mesh: `{face["gaze"]["eyeball_mesh"]}`.', '']
        if face['problems']:
            out += ['Problems found:', ''] + [f'- {p}' for p in face['problems']]
        else:
            out.append('No problems found.')
        synced = [n for n, t in face['baked_tracks'].items() if t.get('in_sync')]
        out += ['', f'Face clip in sync with body clip: {len(synced)} of {len(face["baked_tracks"])} signs.']

    path = ROOT / 'reports' / 'VALIDATION_SUMMARY.md'
    path.write_text('\n'.join(out) + '\n', encoding='utf-8')
    print(f'Wrote {path}')


if __name__ == '__main__':
    main()
